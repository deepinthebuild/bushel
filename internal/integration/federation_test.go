func TestFederationPublishesExternalUploadsWithoutForwarding(t *testing.T) {
	ctx, cancel := context.WithTimeout(t.Context(), 45*time.Second)
	defer cancel()
	external, err := publication.ParsePolicy("external")
	if err != nil {
		t.Fatal(err)
	}
	all, err := publication.ParsePolicy("all")
	if err != nil {
		t.Fatal(err)
	}
	source := newFederationPeer(t, ctx, false, external)
	receivers := []*federationPeer{
		newFederationPeer(t, ctx, true, all),
		newFederationPeer(t, ctx, true, all),
	}
	optedOut := newFederationPeer(t, ctx, false, all)
	witness := newFederationPeer(t, ctx, true, all)
	for _, receiver := range receivers {
		connectFederationPeer(t, ctx, source, receiver)
		connectFederationPeer(t, ctx, receiver, witness)
	}
	connectFederationPeer(t, ctx, source, optedOut)
	awaitFederation(t, ctx, "seed capability negotiation", func() bool {
		peers := source.node.SeedPeers()
		return len(peers) == 2 && slices.Contains(peers, receivers[0].node.ID()) &&
			slices.Contains(peers, receivers[1].node.ID()) &&
			slices.Contains(receivers[0].node.SeedPeers(), witness.node.ID()) &&
			slices.Contains(receivers[1].node.SeedPeers(), witness.node.ID())
	})

	// External-only publication leaves ordinary local CAS uploads intact.
	mainData := []byte("a main-workspace output")
	unknownData := []byte("an upload with no request metadata")
	coalescedUnknown := []byte("an unrelated member of a coalesced upload")
	uploadFederationBatch(t, federationMetadata(t, ctx, "//app:binary"), source.client, mainData)
	uploadFederationBatch(t, ctx, source.client, unknownData)

	// Cover tiny, typical, and mapped blobs with deterministic generated bytes.
	// A missing observation associates only its own digest; it cannot start a
	// pull before the subsequent metadata-free, coalesced upload commits it.
	eligible := [][]byte{
		cachePayload(cachePayloadCase{size: 1, seed: 7}),
		cachePayload(cachePayloadCase{size: 256<<10 + 13, seed: 23}),
		cachePayload(cachePayloadCase{size: cas.MaxChunkSize + 1, seed: 47}),
	}
	associated := cas.Sum(eligible[2])
	missing, err := repb.NewContentAddressableStorageClient(source.client).FindMissingBlobs(
		federationMetadata(t, ctx, "@@dependency+1.0//src:archive"),
		&repb.FindMissingBlobsRequest{BlobDigests: []*repb.Digest{{Hash: associated.Hex(), SizeBytes: associated.Size}}},
	)
	if err != nil || len(missing.GetMissingBlobDigests()) != 1 {
		t.Fatalf("FindMissing before upload: %v, %v", missing, err)
	}
	awaitFederation(t, ctx, "missing digest association", func() bool {
		return source.publisher.Stats().Waiting == 1
	})
	if stats := source.publisher.Stats(); stats.Records != 1 || stats.ChargedOffers != 0 {
		t.Fatalf("missing or excluded uploads started publication: %+v", stats)
	}
	for _, receiver := range receivers {
		assertFederationAbsent(t, ctx, receiver, eligible[2])
	}
	uploadFederationBatch(t, ctx, source.client, eligible[2], coalescedUnknown)
	externalContext := federationMetadata(t, ctx, "@@dependency+1.0//src:object")
	uploadFederationBatch(t, externalContext, source.client, eligible[0])
	if err := uploadCachedPayload(externalContext, source.client, eligible[1]); err != nil {
		t.Fatalf("external ByteStream upload: %v", err)
	}
	awaitFederation(t, ctx, "two verified remote copies of each eligible blob", func() bool {
		stats := source.publisher.Stats()
		if stats.PersistenceFailed || stats.Dropped != 0 {
			t.Fatalf("publication lost work: %+v", stats)
		}
		return stats.Completed == len(eligible)
	})
	stats := source.publisher.Stats()
	if stats.Records != len(eligible) || stats.ChargedOffers != publication.ReplicaTarget*len(eligible) {
		t.Fatalf("excluded traffic or opted-out peers affected replica accounting: %+v", stats)
	}
	for _, receiver := range receivers {
		for _, data := range eligible {
			present, err := receiver.store.Committed(ctx, cas.Sum(data))
			if err != nil || !present {
				t.Fatalf("receipt preceded receiver CAS publication: present=%t, err=%v", present, err)
			}
		}
	}

	// Receiver RPCs have no fetcher. These reads must be served from their own
	// verified storage even after the original source has fully shut down.
	source.close()
	for _, receiver := range receivers {
		for _, data := range eligible {
			if err := readCachedPayload(ctx, receiver.client, data); err != nil {
				t.Fatalf("receiver read after source shutdown: %v", err)
			}
		}
		for _, data := range [][]byte{mainData, unknownData, coalescedUnknown} {
			assertFederationAbsent(t, ctx, receiver, data)
		}
		// A missing observation is a queue barrier: after it is processed, all
		// earlier seed completions and reads have had a chance to create work.
		// Its one waiting record must be the receiver's only publication intent.
		barrier := cas.Sum([]byte("an absent receiver publication barrier"))
		response, err := repb.NewContentAddressableStorageClient(receiver.client).FindMissingBlobs(ctx,
			&repb.FindMissingBlobsRequest{BlobDigests: []*repb.Digest{{Hash: barrier.Hex(), SizeBytes: barrier.Size}}})
		if err != nil || len(response.GetMissingBlobDigests()) != 1 {
			t.Fatalf("receiver publication barrier: %v, %v", response, err)
		}
		awaitFederation(t, ctx, "receiver publication queue barrier", func() bool {
			return receiver.publisher.Stats().Waiting == 1
		})
		if stats := receiver.publisher.Stats(); stats.Records != 1 || stats.ChargedOffers != 0 {
			t.Fatalf("received blobs or cache reads created forwarding intent: %+v", stats)
		}
	}
	for _, uninvolved := range []*federationPeer{optedOut, witness} {
		for _, data := range eligible {
			assertFederationAbsent(t, ctx, uninvolved, data)
		}
	}
}

type federationPeer struct {
	node      *p2p.Node
	store     *cas.Store
	publisher *publication.Publisher
	client    *grpc.ClientConn
	close     func()
}

func newFederationPeer(t *testing.T, ctx context.Context, acceptSeeds bool, policy publication.Policy) *federationPeer {
	t.Helper()
	root := t.TempDir()
	p := &federationPeer{}
	var listener net.Listener
	var server *grpc.Server
	p.close = sync.OnceFunc(func() {
		if p.publisher != nil {
			if err := p.publisher.Close(); err != nil {
				t.Errorf("close publisher: %v", err)
			}
		}
		if p.client != nil {
			_ = p.client.Close()
		}
		if server != nil {
			server.Stop()
		}
		if listener != nil {
			_ = listener.Close()
		}
		if p.node != nil {
			if err := p.node.Close(); err != nil {
				t.Errorf("close peer: %v", err)
			}
		}
		if p.store != nil {
			if err := p.store.Close(); err != nil {
				t.Errorf("close store: %v", err)
			}
		}
	})
	t.Cleanup(p.close)
	backend := teststorage.New()
	var err error
	p.store, err = cas.NewStore(filepath.Join(root, "cas"), 32<<20,
		cas.Backend{Chunks: backend.Chunks, Mappings: backend.Mappings})
	if err != nil {
		t.Fatal(err)
	}
	key, _, err := crypto.GenerateEd25519Key(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	p.node, err = p2p.New(ctx, p2p.Config{Store: p.store, PrivateKey: key,
		Listen: []string{"/ip4/127.0.0.1/tcp/0"}, RequestTimeout: 5 * time.Second,
		AcceptSeeds: acceptSeeds, SeedMaxBlobBytes: 4 << 20, SeedBytesPerHour: 32 << 20})
	if err != nil {
		t.Fatal(err)
	}
	p.publisher, err = publication.New(ctx, filepath.Join(root, "publication"), p.store, p.node,
		publication.Options{Policy: policy, BytesPerHour: 32 << 20, Timeout: 10 * time.Second})
	if err != nil {
		t.Fatal(err)
	}
	listener, err = net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	server = reapi.New(p.store, nil, "").WithPublicationObserver(p.publisher).GRPC()
	go func() { _ = server.Serve(listener) }()
	p.client, err = grpc.NewClient(listener.Addr().String(), grpc.WithTransportCredentials(insecure.NewCredentials()))
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func connectFederationPeer(t *testing.T, ctx context.Context, from, to *federationPeer) {
	t.Helper()
	address, err := ma.NewMultiaddr(to.node.Addrs()[0])
	if err != nil {
		t.Fatal(err)
	}
	info, err := peer.AddrInfoFromP2pAddr(address)
	if err != nil {
		t.Fatal(err)
	}
	if err := from.node.Connect(ctx, *info); err != nil {
		t.Fatal(err)
	}
}

func federationMetadata(t *testing.T, ctx context.Context, target string) context.Context {
	t.Helper()
	encoded, err := proto.Marshal(&repb.RequestMetadata{ToolInvocationId: "federation-test", ActionId: target, TargetId: target})
	if err != nil {
		t.Fatal(err)
	}
	return metadata.NewOutgoingContext(ctx, metadata.Pairs(workspace.MetadataHeader, string(encoded)))
}

func uploadFederationBatch(t *testing.T, ctx context.Context, client *grpc.ClientConn, payloads ...[]byte) {
	t.Helper()
	request := &repb.BatchUpdateBlobsRequest{}
	for _, data := range payloads {
		d := cas.Sum(data)
		request.Requests = append(request.Requests, &repb.BatchUpdateBlobsRequest_Request{
			Digest: &repb.Digest{Hash: d.Hex(), SizeBytes: d.Size}, Data: data,
		})
	}
	response, err := repb.NewContentAddressableStorageClient(client).BatchUpdateBlobs(ctx, request)
	if err != nil || len(response.GetResponses()) != len(payloads) {
		t.Fatalf("batch upload: %v, %v", response, err)
	}
	for _, result := range response.Responses {
		if result.GetStatus().GetCode() != 0 {
			t.Fatalf("batch upload item: %v", result.GetStatus())
		}
	}
}

func assertFederationAbsent(t *testing.T, ctx context.Context, p *federationPeer, data []byte) {
	t.Helper()
	present, err := p.store.Committed(ctx, cas.Sum(data))
	if err != nil || present {
		t.Fatalf("unexpected replica at %s: present=%t, err=%v", p.node.ID(), present, err)
	}
}

func awaitFederation(t *testing.T, ctx context.Context, description string, ready func() bool) {
	t.Helper()
	ticker := time.NewTicker(25 * time.Millisecond)
	defer ticker.Stop()
	for !ready() {
		select {
		case <-ctx.Done():
			t.Fatalf("waiting for %s: %v", description, ctx.Err())
		case <-ticker.C:
		}
	}
}
